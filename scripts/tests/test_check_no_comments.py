import importlib.util
import subprocess
import sys
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parents[1] / "check_no_comments.py"

_spec = importlib.util.spec_from_file_location("check_no_comments", SCRIPT)
cnc = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(cnc)


def _diff(path: str, start: int, added: list[str]) -> str:
    body = "\n".join(f"+{line}" for line in added)
    return (
        f"diff --git a/{path} b/{path}\n"
        f"--- a/{path}\n"
        f"+++ b/{path}\n"
        f"@@ -1,1 +{start},{len(added)} @@\n"
        f"{body}\n"
    )


@pytest.mark.parametrize(
    ("path", "lines", "expected"),
    [
        ("svc.go", ["// explain the retry"], 1),
        ("svc.go", ["//nolint:govet"], 0),
        ("svc.go", ["// go:build linux"], 0),
        ("svc.go", ["//go:embed file.txt"], 0),
        ("svc.go", ["// Code generated by sqlc. DO NOT EDIT."], 0),
        ("svc.go", ['u := "https://example.com/x"'], 0),
        ("mod.py", ["# explain the retry"], 1),
        ("mod.py", ["# noqa: BLE001"], 0),
        ("mod.py", ["# type: ignore[arg-type]"], 0),
        ("mod.py", ["#!/usr/bin/env python3"], 0),
        ("app.ts", ["// explain the retry"], 1),
        ("app.ts", ["// eslint-disable-next-line no-console"], 0),
        ("app.ts", ["// @ts-expect-error"], 0),
        ("app.tsx", ["/* block comment */"], 1),
        ("app.ts", ['const u = "http://example.com";'], 0),
        ("notes.md", ["# heading"], 0),
        ("schema.sql", ["-- migration note"], 0),
        ("run.sh", ["# explain"], 0),
    ],
)
def test_find_violations(path, lines, expected):
    assert len(cnc.find_violations(_diff(path, 10, lines))) == expected


def test_find_violations_skips_files_that_declare_themselves_generated(tmp_path):
    generated = tmp_path / "schema.d.ts"
    generated.write_text(
        "/**\n"
        " * This file was auto-generated by openapi-typescript.\n"
        " * Do not make direct changes to the file.\n"
        " */\n"
    )
    diff = _diff(str(generated), 4, ["/** @description Cache probe result. */"])
    assert cnc.find_violations(diff) == []


def test_find_violations_still_flags_handwritten_files(tmp_path):
    handwritten = tmp_path / "api.d.ts"
    handwritten.write_text("export interface HealthServices {\n")
    diff = _diff(str(handwritten), 2, ["/** @description Cache probe result. */"])
    assert len(cnc.find_violations(diff)) == 1


def test_line_numbers_track_the_hunk():
    diff = _diff("svc.go", 7, ["ok := true", "// banned", "also := false"])
    assert cnc.find_violations(diff) == [("svc.go", 8, "// banned")]


def test_context_and_removed_lines_are_ignored():
    diff = (
        "diff --git a/svc.go b/svc.go\n"
        "--- a/svc.go\n"
        "+++ b/svc.go\n"
        "@@ -1,3 +1,3 @@\n"
        " // pre-existing comment\n"
        "-// removed comment\n"
        "+ok := true\n"
    )
    assert cnc.find_violations(diff) == []


def _run_cli(cwd: Path) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(SCRIPT), "--staged"],
        cwd=cwd,
        capture_output=True,
        text=True,
    )


def _init_repo(tmp_path: Path) -> None:
    subprocess.run(["git", "init", "-q"], cwd=tmp_path, check=True)


def test_cli_passes_a_comment_free_stage(tmp_path):
    _init_repo(tmp_path)
    (tmp_path / "svc.go").write_text("package svc\n\nfunc F() int { return 1 }\n")
    subprocess.run(["git", "add", "svc.go"], cwd=tmp_path, check=True)

    result = _run_cli(tmp_path)
    assert result.returncode == 0, result.stderr


def test_cli_rejects_a_comment_and_names_it(tmp_path):
    _init_repo(tmp_path)
    (tmp_path / "svc.go").write_text("package svc\n\n// why this exists\n")
    subprocess.run(["git", "add", "svc.go"], cwd=tmp_path, check=True)

    result = _run_cli(tmp_path)
    assert result.returncode == 1
    assert "svc.go" in result.stderr
    assert "// why this exists" in result.stderr
